"""Adapt EDCB Unix macros to the unmodified Rust registration tool."""
from datetime import datetime, timedelta, timezone
import os
from pathlib import Path
import sys
import re
import shutil
import tempfile


def environment(source):
    result = dict(source)
    for original, target in [('FilePath', 'FILEPATH'), ('FileName', 'FILENAME'), ('Title', 'TITLE')]:
        result[target] = source[original]
    start = datetime.fromisoformat(source['StartTime']).astimezone(timezone(timedelta(hours=9)))
    end = start + timedelta(seconds=int(source['DurationSecond']))
    for prefix, moment in [('S', start), ('E', end)]:
        for suffix, fmt in [('DYYYY', '%Y'), ('DMM', '%m'), ('DDD', '%d'), ('THH', '%H'), ('TMM', '%M'), ('TSS', '%S')]:
            result[prefix + suffix] = moment.strftime(fmt)
    return result


def runtime_for_recording(runtime, filepath):
    # Match the mount layout generated by storage.py. Keep the source disk for
    # the default edcb destination; custom destinations remain user-controlled.
    match = re.match(r'^/(recorded(?:[2-9]|[1-9][0-9]+))/edcb/', filepath)
    if not match:
        return runtime
    import yaml
    settings = yaml.safe_load((runtime / 'config.yml').read_text())
    upload = settings['epgstationUpload']
    if upload['parentDirectoryName'] != 'edcb':
        return runtime
    number = match[1][len('recorded'):]
    upload['parentDirectoryName'] = 'edcb' + number
    directory = runtime / match[1]
    directory.mkdir(exist_ok=True)
    # The Rust tool locates its config beside the real executable, so use a copy.
    binary = directory / 'edcb_to_epgstation_ts'
    with tempfile.NamedTemporaryFile(dir=directory, delete=False) as stream:
        next_binary = Path(stream.name)
    shutil.copy2(runtime / binary.name, next_binary)
    next_binary.replace(binary)
    with tempfile.NamedTemporaryFile(mode='w', dir=directory, delete=False) as stream:
        yaml.safe_dump(settings, stream, allow_unicode=True)
        temporary = Path(stream.name)
    temporary.replace(directory / 'config.yml')
    return directory


if __name__ == '__main__':
    runtime = Path(os.environ.get('EDCB_UPLOAD_RUNTIME', '/var/local/edcb/upload'))
    if len(sys.argv) == 1:
        runtime = runtime_for_recording(runtime, os.environ['FilePath'])
    tool = runtime / 'edcb_to_epgstation_ts'
    env = dict(os.environ) if len(sys.argv) > 1 else environment(os.environ)
    os.execve(str(tool), [str(tool), *sys.argv[1:]], env)
